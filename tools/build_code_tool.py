"""Build the single uploadable Samvaad code tool for Disha.

  .venv/bin/python -I tools/build_code_tool.py

Reads samvaad/code_tool/disha_tools_src.py and replaces its `# @@PERSONA_GENERATOR@@` marker with the persona
generator (generator/generate.py, decision logic only) made self-contained: fixed_script constants, the state ->
region table from data_prep/evidence.py, and the evidence numbers the generator cites (outputs/evidence.json,
trimmed). Writes samvaad/code_tool/disha_tools.py, the file to upload. The generator stays the single source of truth.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from data_prep.evidence import REGION  # noqa: E402
from generator import fixed_script as FS  # noqa: E402

SRC = ROOT / "samvaad" / "code_tool" / "disha_tools_src.py"
OUT = ROOT / "samvaad" / "code_tool" / "disha_tools.py"
MARKER = "# @@PERSONA_GENERATOR@@"


def _replace(text: str, old: str, new: str) -> str:
    if old not in text:
        raise SystemExit(f"build_code_tool: expected text not found in generator source:\n{old[:120]}")
    return text.replace(old, new, 1)


def generator_bundle() -> str:
    src = (ROOT / "generator" / "generate.py").read_text()
    # decision logic only: drop the module docstring and everything from the data-access section on
    src = src[src.index('"""', 3) + 3:]
    src = src[:re.search(r"^# -+ data access", src, re.M).start()]
    for line in ("import argparse\n", "from pathlib import Path\n", "from generator import fixed_script as FS\n",
                 'ROOT = Path(__file__).resolve().parent.parent\n', 'OUT = ROOT / "outputs"\n'):
        src = _replace(src, line, "")
    src = _replace(src, "REGION = None  # filled lazily from data_prep.evidence to keep one source of truth",
                   "REGION = " + repr(REGION))
    src = _replace(src, '''    global REGION
    if REGION is None:
        from data_prep.evidence import REGION as R
        REGION = R
''', "")
    src = re.sub(r'@lru_cache\(maxsize=1\)\ndef evidence\(\):\n(?:    .*\n)+?    return json\.loads\(p\.read_text\(\)\)\n',
                 "def evidence():\n    return EVIDENCE\n", src, count=1)
    if "return EVIDENCE" not in src:
        raise SystemExit("build_code_tool: could not replace evidence()")

    ev = json.loads((ROOT / "outputs" / "evidence.json").read_text())
    slim = {"items": [{k: i.get(k) for k in ("id", "key", "n", "value", "baseline", "strength")} for i in ev["items"]],
            **{k: ev.get(k, {}) for k in ("language_by_state", "english_mix", "objection_mix")}}
    fs = ("class FS:\n    \"\"\"generator/fixed_script.py constants.\"\"\"\n"
          f"    FACTS = {FS.FACTS!r}\n    LEAD_REASON_BY_BUCKET = {FS.LEAD_REASON_BY_BUCKET!r}\n"
          f"    GUARDRAILS = {FS.GUARDRAILS!r}\n")
    head = ("# ===== persona generator: generated by tools/build_code_tool.py from generator/generate.py =====\n"
            "import math\nimport re\nfrom functools import lru_cache\n\n"
            f"EVIDENCE = json.loads({json.dumps(json.dumps(slim, ensure_ascii=False), ensure_ascii=False)})\n\n" + fs)
    body = src.replace("\nimport json\nimport math\nimport re\nfrom functools import lru_cache\n", "\n")
    return head + body.rstrip() + "\n# ===== end persona generator =====\n"


def main():
    src = SRC.read_text()
    if src.count(MARKER) != 1:
        raise SystemExit(f"build_code_tool: {SRC.name} must contain {MARKER} exactly once")
    out = src.replace(MARKER, generator_bundle())
    compile(out, str(OUT), "exec")
    OUT.write_text(out)
    print(f"wrote {OUT.relative_to(ROOT)} ({len(out.encode()):,} bytes, {out.count(chr(10)):,} lines)")


if __name__ == "__main__":
    main()
